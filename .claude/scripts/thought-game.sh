#!/bin/bash
# ============================================
# 思维博弈引擎 — 预测偏差自动触发深度复盘
# 用法: bash thought-game.sh <场次> <预测> <实际> <推理链文件>
# ============================================

MATCH="$1"
PREDICTED="$2"
ACTUAL="$3"
CHAIN_FILE="${4:-.claude/evolution/betting/calibrations/latest.md}"

GAME_DIR=".claude/evolution/betting/thought-games"
mkdir -p "$GAME_DIR"

TIMESTAMP=$(date +%Y-%m-%d_%H%M%S)
GAME_FILE="$GAME_DIR/$TIMESTAMP-$MATCH.md"

echo "========================================"
echo "  🧠 思维博弈引擎"
echo "  偏差触发 → 深度复盘 → 思维路径修正"
echo "========================================"

# 检查是否偏差
if [ "$PREDICTED" = "$ACTUAL" ]; then
  echo ""
  echo "  ⚠️  表面一致——但必须深度审查推理链!"
  echo "  预测: $PREDICTED"
  echo "  实际: $ACTUAL"
  echo ""
  echo "  结果对了≠推理对了。成功不审查是最危险的思维陷阱。"
  echo "  强制进入思维博弈——验证每一步推理是否站得住。"
  echo ""
  MODE="surface_match"
else
  echo ""
  echo "  ⚠️  预测偏差触发!"
  echo "  预测: $PREDICTED"
  echo "  实际: $ACTUAL"
  echo ""
  MODE="deviation"
fi

echo ""
echo "  ⚠️  预测偏差触发!"
echo "  预测: $PREDICTED"
echo "  实际: $ACTUAL"
echo ""

cat > "$GAME_FILE" << GAMEEOF
# 思维博弈 — $MATCH

**触发时间:** $TIMESTAMP
**预测:** $PREDICTED
**实际:** $ACTUAL
**模式:** $MODE
$([ "$MODE" = "surface_match" ] && echo "**⚠️ 表面一致——结果对了≠推理对了。必须审查每一步是否站得住。**")

---

## 第一轮: 追问"为什么对/错"

### 问题 1: $([ "$MODE" = "surface_match" ] && echo "推理真的对吗？还是运气？" || echo "错在哪一步?")
- [ ] 数据解析错误? (parse_odds 输出是否准确)
- [ ] OO-EPC 概率转换偏差? (市场共识是否被误读)
- [ ] Kelly 评估参数问题? (EV阈值/divisor是否合理)
- [ ] 推理逻辑跳跃? (从概率到决策的链条是否完整)
- [ ] 外部因素遗漏? (伤病/天气/战意等非量化因素)

### 问题 2: 哪条推理链断了?
\`\`\`
市场观察 → ______ (这一步对吗?)
  → OO-EPC概率 → ______ (转换有问题吗?)
    → Kelly评估 → ______ (参数对吗?)
      → 决策 → ______ (逻辑完整吗?)
\`\`\`

### 问题 3: 如果当时换个角度思考呢?
- 如果不用OO-EPC，用层次Poisson会怎样?
- 如果不看竞彩赔率，看Pinnacle会怎样?
- 如果考虑主场优势加权呢?
- 如果考虑近期状态/伤病呢?

---

## 第二轮: 回推推理过程

### 逐步验证
1. 数据源: 500.com 欧赔/亚盘/凯利数据完整吗? ______
2. 竞彩位置: 竞彩官方在赔率列表中的位置? ______
3. 市场信号: 赔率变化方向(Pinnacle)支持预测吗? ______
4. 共识强度: 52家公司极差多少? 共识还是分歧? ______
5. Kelly计算: EV/Full Kelly/Quarter Kelly 数值? ______

### 假设检验
| 假设 | 成立? | 如果不成立，正确路径是什么? |
|------|:-----:|--------------------------|
| 市场有效定价 | | |
| 主场优势已反映 | | |
| 赔率变化是信息驱动 | | |
| OO-EPC转换准确 | | |

---

## 第三轮: 寻找正确的思维路径

### 事后视角: 如果当时这样思考...
(从实际结果反向推导——什么信号应该被注意到但被忽略了?)

1. 信号遗漏: ________________
2. 过度依赖: ________________
3. 本应考虑: ________________

### 正确的思维路径应该是什么?
\`\`\`
如果当时:
  1. 先看 ______ (而不是 ______)
  2. 再查 ______ (而不是 ______)
  3. 最后问 ______ (而不是 ______)
→ 可能得出更接近实际的结论
\`\`\`

---

## 博弈结论

### 本次错误的本质
(不是"运气不好"——是哪个思维陷阱?)

### 下次遇到类似情况的正确做法
1. ________________
2. ________________
3. ________________

### 这个错误是否重复发生?
- 上次类似错误: ______ (日期/场次)
- 如果重复: ⚠️ 升级为最高优先级修复

---

*思维博弈完成时间: _____*
*下一次比赛前必须重新加载此文件*
GAMEEOF

echo "  📄 思维博弈文件: $GAME_FILE"
echo ""
echo "  🧠 请现在逐轮填写思维博弈内容"
echo "  📋 填写完成后运行: bash betting-evolve.sh $MATCH"
echo ""
echo "========================================"
echo "  思维博弈三不原则:"
echo "  不找借口 — 不说'运气不好'"
echo "  不跳步骤 — 逐轮逐问回答"
echo "  不过夜 — 比赛结束后立即触发"
echo "========================================"
